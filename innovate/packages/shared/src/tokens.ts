export type ColorToken = keyof (typeof colors)["dark"];

/** Font sizes in px with line heights. Pro-tool density: the body size is 13px. */
export const typeScale = {
  "2xs": [10, 14],
  xs: [11, 16],
  sm: [12, 18],
  base: [13, 20],
  md: [14, 22],
  lg: [16, 24],
  xl: [20, 28],
  "2xl": [28, 34],
  "3xl": [40, 46],
} as const;

/** Base spacing unit; Tailwind's p-1 = 4px, p-2 = 8px, ... */
export const spacingUnit = 4;

export const radii = { xs: 2, sm: 3, md: 5, lg: 8, xl: 12 } as const;

export const fonts = {
  sans: 'var(--font-inter), ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif',
  mono: 'var(--font-jetbrains), ui-monospace, "SF Mono", Menlo, Consolas, monospace',
} as const;

export const motion = { fast: "120ms", base: "180ms", ease: "cubic-bezier(0.2, 0, 0, 1)" } as const;

export function renderTokensCss(): string {
  const lines: string[] = [];
  lines.push("/* GENERATED by packages/shared/scripts/build-tokens.ts from src/tokens.ts. Do not edit; run `pnpm tokens`. */");
  const block = (selector: string, scheme: "dark" | "light") => {
    lines.push(`${selector} {`);
    lines.push(`  color-scheme: ${scheme};`);
    for (const [name, value] of Object.entries(colors[scheme])) lines.push(`  --in-${name}: ${value};`);
    lines.push("}");
  };
  block(':root,\n[data-theme="light"]', "light");
  block('[data-theme="dark"]', "dark");
  lines.push(":root {");
  lines.push(`  --in-ease: ${motion.ease};`);
  lines.push(`  --in-fast: ${motion.fast};`);
  lines.push(`  --in-base: ${motion.base};`);
  lines.push("}");
  lines.push("@theme inline {");
  lines.push(`  --spacing: ${spacingUnit}px;`);
  for (const name of Object.keys(colors.dark)) lines.push(`  --color-${name}: var(--in-${name});`);
  for (const [name, [size, lh]] of Object.entries(typeScale)) {
    lines.push(`  --text-${name}: ${size}px;`);
    lines.push(`  --text-${name}--line-height: ${lh}px;`);
  }
  for (const [name, px] of Object.entries(radii)) lines.push(`  --radius-${name}: ${px}px;`);
  lines.push(`  --font-sans: ${fonts.sans};`);
  lines.push(`  --font-mono: ${fonts.mono};`);
  lines.push("}");
  return lines.join("\n") + "\n";
}
