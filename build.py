#!/usr/bin/env python3
"""Generate, check and package the pack.

    python build.py

Writes dist/PulseFX.drfx (the installable bundle), dist/loose/ (the same
templates as plain files), docs/EFFECTS.md and TESTING.md. Exits non-zero and
writes nothing installable if any check fails.
"""

from __future__ import annotations

import shutil
import sys
import zipfile
from pathlib import Path

from vfxpack.definitions import build_all
from vfxpack.simulate import simulate
from vfxpack.validate import validate_bundle, validate_text

ROOT = Path(__file__).parent
DIST = ROOT / "dist"
BUNDLE = DIST / "PulseFX.drfx"

KIND_HEADINGS = {
    "effect": ("Effects", "Effects Library > Toolbox > Effects > Fusion Effects > Pulse FX"),
    "cut": ("Cut effects (for adjustment clips over a cut)",
            "Effects Library > Toolbox > Effects > Fusion Effects > Pulse FX Cuts"),
    "transition": ("Transitions", "Effects Library > Toolbox > Video Transitions > Fusion Transitions > Pulse FX"),
}


def effects_doc(macros) -> str:
    out = ["# Effect reference", "",
           "Generated by `build.py` from `vfxpack/definitions.py`. Do not edit by hand.", ""]
    for kind, (heading, where) in KIND_HEADINGS.items():
        out += [f"## {heading}", "", f"Found under: {where}", ""]
        for m in (m for m in macros if m.kind == kind):
            out += [f"### {m.title}", "", m.summary, "", "| Control | What it does |", "|---|---|"]
            out += [f"| {c['label']} | {c['doc']} |" for c in m.controls]
            out.append("")
    return "\n".join(out)


def testing_doc(macros, evaluations: int) -> str:
    out = [TESTING_HEAD.format(count=len(macros), evaluations=f"{evaluations:,}")]
    for kind, (heading, where) in KIND_HEADINGS.items():
        out += [f"## {heading}", "", f"Should appear under: **{where}**", ""]
        for m in (m for m in macros if m.kind == kind):
            out += [
                f"### {m.title}", "",
                f"- [ ] **Appears** in the library under the bin above.",
                f"- [ ] **Apply:** {m.apply}",
                f"- [ ] **Expect:** {m.expect}",
                f"- [ ] **Controls:** all of these show in the Inspector: "
                + ", ".join(c["label"] for c in m.controls) + ".",
                f"- [ ] **Try:** {m.tryout}",
                f"- [ ] **Retime:** trim the clip (or transition) to half and double length; the "
                "animation should stretch to fit with nothing cut off.",
                "",
            ]
    out.append(TESTING_TAIL)
    return "\n".join(out)


TESTING_HEAD = """# Test checklist

Generated by `build.py`. Do not edit by hand.

Nothing in this pack has been loaded in Resolve yet. The build confirmed the
files parse, use only tool and input names seen in real Resolve files, and that
the animation maths is right ({count} templates, {evaluations} expression
evaluations). It could not confirm that Resolve accepts each template or how
any of them look. This checklist is how we find out.

## Before you start

1. Quit Resolve. Run `install.bat` (or copy `dist/PulseFX.drfx` as the README describes).
2. Start Resolve Studio 21, open a 1080p or UHD timeline with at least three
   clips on V1 that have spare media either side of their cuts.
3. Open the Effects Library on the Edit page.

## First pass: did they load?

Check the three bins below exist and count the items: 5 in *Pulse FX* effects,
4 in *Pulse FX Cuts*, 2 in *Pulse FX* transitions. Tell me which are missing
before testing looks: a missing template means Resolve rejected the file, and
that is the most useful single fact you can send back.

If the whole pack is missing, try `install.bat loose`, restart Resolve and look
again. That tells us whether the problem is the bundle or the templates.
"""

TESTING_TAIL = """## Things I assumed that only Resolve can confirm

Each of these was seen in real files, but its meaning or behaviour is inferred.
If an effect misbehaves, the matching row is the first suspect.

| Assumption | Used by | If it is wrong you will see |
|---|---|---|
| Transform `Edges = 3` means Mirror | Shake, RGB Split, Glitch, all Cuts | Black or stretched edges instead of mirrored picture |
| DirectionalBlur `Type = 2` is Centered and `3` is Zoom | Whip Pan, Zoom Punch, Zoom Through | A streak in the wrong style (e.g. zoom rays on the whip pan) |
| Displace `Type = 1` is X/Y and channel `4` is Luminance | Digital Glitch, Glitch Cut | Bands bulge radially, or nothing tears |
| A dropdown made by overriding a Custom tool slider returns the option index from 0 | Envelope, Direction | Dropdown shows as a slider, or picks the wrong behaviour |
| Anim Curves `Source = Duration` spans the clip when the effect sits on an adjustment clip | all Cuts | Animation runs at the wrong speed or never reaches the end |
| Transform motion blur re-evaluates expressions between frames | Spin, Camera Shake (Motion Blur on) | No blur, or stepped ghost copies |
| FastNoise with `XScale = 0.05` gives horizontal bands; brightness -0.5 leaves about half the rows untouched | Digital Glitch, Glitch Cut | Blobs instead of strips, or the whole frame shifts |
| Luma wipe direction and `Softness` range | Luma Wipe | Wipe runs the opposite way, or the edge is hard |

## How to report back

For anything that fails, the most useful things to send, in order:

1. Which templates did not appear at all.
2. For one that appears but misbehaves: what you saw against the **Expect** line.
3. A real exported template from your Resolve. On the Fusion page, build
   anything (even one Transform with Edges set to Mirror), select the node,
   press Ctrl+C and paste into Notepad: the text is the `.setting` syntax.
   I will treat it as ground truth over everything in this repo.
4. Console errors: on the Fusion page open Workspace > Console, then drag a
   `.setting` from `dist/loose/` into the node editor and copy what it prints.
"""


def main() -> int:
    macros = build_all()
    failed = False
    evaluations = 0
    print(f"{'template':<24}{'structure':<12}{'maths':<10}evaluations")
    for m in macros:
        text = m.text()
        structure = validate_text(text, m.category)
        maths, count = simulate(text, m.kind) if not structure else ([], 0)
        evaluations += count
        print(f"{m.title:<24}{'ok' if not structure else 'FAIL':<12}{'ok' if not maths else 'FAIL':<10}{count}")
        for problem in structure + maths:
            failed = True
            print(f"    {problem}")
    if failed:
        print("\nBuild stopped: fix the problems above. Nothing was packaged.")
        return 1

    if DIST.exists():
        shutil.rmtree(DIST)
    loose = DIST / "loose"
    with_paths = sorted((m.relpath, m.text()) for m in macros)
    for relpath, text in with_paths:
        target = loose / relpath
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
    with zipfile.ZipFile(BUNDLE, "w", zipfile.ZIP_DEFLATED) as bundle:
        for relpath, text in with_paths:
            info = zipfile.ZipInfo(relpath, date_time=(2026, 1, 1, 0, 0, 0))  # stable output
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            bundle.writestr(info, text.encode("utf-8"))
    problems = validate_bundle(str(BUNDLE))
    for problem in problems:
        print(f"    {problem}")
    if problems:
        BUNDLE.unlink()
        print("\nBundle check failed; bundle removed.")
        return 1

    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "EFFECTS.md").write_text(effects_doc(macros), encoding="utf-8", newline="\n")
    (ROOT / "TESTING.md").write_text(testing_doc(macros, evaluations), encoding="utf-8", newline="\n")
    print(f"\n{len(macros)} templates passed. Wrote {BUNDLE.relative_to(ROOT)} "
          f"({BUNDLE.stat().st_size:,} bytes), dist/loose/, docs/EFFECTS.md, TESTING.md.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
